def free_cols(name, ties, pick_mode):
    shape = dict((a, b) for a, b, _ in CELLS)[name]
    k = 1
    for d in shape:
        k *= d
    if name == "pick" and pick_mode == "fixed":
        return []
    if "inv" in ties and name in ("sub_d", "sub_b"):
        return []
    if "sym" in ties and name in ("add_d", "add_c"):
        return [(u * 10 + v) * 2 + c for u in range(10)
                for v in range(u, 10) for c in range(2)]
    return list(range(k))


def cell_index(only=None, ties=(), pick_mode="learned"):
    out = []
    for name, shape, n in CELLS:
        if only is not None and name not in only:
            continue
        for c in free_cols(name, ties, pick_mode):
            out.append((name, c, n))
    return out


