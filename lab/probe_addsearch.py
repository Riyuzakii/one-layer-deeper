def structure_scores(snap, ndigits):
    out = {}
    for nm, T, cols in (("add_shift", snap["add_d"], range(10)),
                        ("sub_shift", snap["sub_d"], sorted(set(ndigits)))):
        k = n = 0
        T = T.cpu()
        for v in cols:
            for c in range(T.shape[2]):
                a = T[:, v, c]
                k += max(sum(1 for u in range(10) if int(a[u]) == (u + s) % 10)
                         for s in range(10))
                n += 10
        out[nm] = round(k / n, 3)
    sh = set()
    T = snap["add_d"].cpu()
    for v in range(10):
        for c in range(T.shape[2]):
            a = T[:, v, c]
            best, bs = -1, 0
            for s in range(10):
                m = sum(1 for u in range(10) if int(a[u]) == (u + s) % 10)
                if m > best:
                    best, bs = m, s
            sh.add(bs)
    out["n_shifts"] = len(sh)
    pk = snap["pick"].cpu()
    out["pick_ok"] = round(sum(1 for d in range(10)
                               if int(pk[d]) == d) / 10, 3)
    return out


def cell_agreement(snap, truth):
    out = {}
    tot = agr = 0
    for name, shape, _ in CELLS:
        a, b = snap[name], truth[name]
        k = int((a == b).sum())
        n = a.numel()
        out[name] = round(k / n, 3)
        tot += n
        agr += k
    out["all"] = round(agr / tot, 3)
    return out


