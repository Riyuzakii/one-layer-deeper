#!/usr/bin/env python
"""LAB ONLY -- the ADD-ONLY transducer as a differentiable model with a
POPULATION of independent replicas (the `alu-population` instrument).

HYPOTHESIS.  `alu-relational` proved `Tmul`'s ~200 cells unidentifiable from
anything legal.  So delete `Tmul` from the hypothesis class rather than try to
identify it: accumulate `x^2` from the digits of `x` over a chain of multiples
of `x` generated by the LEARNED adder.  Every learned arithmetic tensor is then
an adder cell (or, under `--tie-sub`, an adder cell read backwards).

The reduction, the place-value shifts and the tree summation are `alu-depth`'s
verified `tree:quotient` schedule, unchanged.  The ONLY difference from
`probe_pop.PopALU` is that the S^2 `Tmul` digit products are replaced by S
full-width multiples of `x` drawn from the adder chain.

VARIANTS (see lab/reports/hard-add-only.md section 2 for the compliance ruling)
  --pick learned  PRIMARY / conservative.  A learned 10x10 table maps the input
                  digit to a chain element.  The architecture asserts only that
                  the leaf at place i is SOME element of the chain generated by
                  repeatedly applying the learned binary op to x -- the same
                  assertion `DigitALU.multiples()` already makes about N.
  --pick fixed    BORDERLINE.  The digit one-hot indexes the chain directly,
                  i.e. `d*x = x added d times` is asserted by the architecture.

COMPLIANCE.  `--construct` (sets tables to truth) and `--tf` (teacher forcing
off a constructed tape) are LAB DIAGNOSTICS and can never be a submission
(rules 2, 7).  `--tf 0` with `--construct` absent is the LEGAL objective.
Self-generated operands only; nothing under data/generated/ is opened.
"""

