def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--pop", type=int, default=8)
    ap.add_argument("--modulus", type=int, default=10403)
    ap.add_argument("--modulus-bits", type=int, default=0)
    ap.add_argument("--modulus-seed", type=int, default=7)
    ap.add_argument("--slots", type=int, default=5)
    ap.add_argument("--train-x", type=int, default=8000)
    ap.add_argument("--held-x", type=int, default=1024)
    ap.add_argument("--max-quot", type=int, default=10)
    ap.add_argument("--pick", default="learned", choices=["learned", "fixed"])
    ap.add_argument("--tie", action="store_true")
    ap.add_argument("--tie-sub", action="store_true")
    ap.add_argument("--tf", type=float, default=0.0,
                    help="DIAGNOSTIC teacher-forced local CE weight; 0 = LEGAL")
    ap.add_argument("--tf-p", type=float, default=1.0)
    ap.add_argument("--sel", type=float, default=1.0)
    ap.add_argument("--sel-tau", type=float, default=1.0)
    ap.add_argument("--sel-hard", action="store_true")
    ap.add_argument("--sel-lr", type=float, default=None)
    ap.add_argument("--steps", type=int, default=1000)
    ap.add_argument("--batch", type=int, default=512)
    ap.add_argument("--lr", type=float, default=3e-2)
    ap.add_argument("--wd", type=float, default=0.0)
    ap.add_argument("--init-scale", type=float, default=0.5)
    ap.add_argument("--clip", type=float, default=1.0)
    ap.add_argument("--global-clip", action="store_true")
    ap.add_argument("--sthard", action="store_true",
                    help="straight-through hard states during TRAINING")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--split-seed", type=int, default=0)
    ap.add_argument("--log-every", type=int, default=250)
    ap.add_argument("--eval-chunk", type=int, default=256)
    ap.add_argument("--eval-n", type=int, default=1024)
    ap.add_argument("--device", default="cuda:0")
    ap.add_argument("--tag", default="")
    ap.add_argument("--construct", action="store_true")
    ap.add_argument("--timing-only", action="store_true")
    ap.add_argument("--jsonl", default="")
    args = ap.parse_args()

    torch.manual_seed(args.seed)
    N, S, P = args.modulus, args.slots, args.pop
    if args.modulus_bits:
        import random
        N, p_, q_ = sample_semiprime(args.modulus_bits,
                                     random.Random(args.modulus_seed))
        print(f"[{args.tag}] sampled N={N} ({args.modulus_bits} bits) "
              f"= {p_}*{q_}", flush=True)
    units = [x for x in range(1, N) if math.gcd(x, N) == 1]
    g = torch.Generator().manual_seed(args.split_seed)
    perm = torch.randperm(len(units), generator=g).tolist()
    tr_x = [units[i] for i in perm[: args.train_x]]
    he_x = [units[i] for i in perm[args.train_x: args.train_x + args.held_x]]
    dev = torch.device(args.device)

    def tens(xs):
        inp = torch.zeros(len(xs), S, 10)
        tgt = torch.zeros(len(xs), S, dtype=torch.long)
        for r, x in enumerate(xs):
            for i, d in enumerate(digits_le(x, S)):
                inp[r, i, d] = 1.0
            for i, d in enumerate(digits_le((x * x) % N, S)):
                tgt[r, i] = d
        return inp.to(dev), tgt.to(dev)

    xin, xt = tens(tr_x)
    hin, ht = tens(he_x)
    W = S + 1
    nd = torch.zeros(W, 10)
    for i, d in enumerate(digits_le(N, W)):
        nd[i, d] = 1.0
    nd = nd.to(dev)
    nd_dig = digits_le(N, W)

    model = PopAddALU(P, S, 2, 2, args.max_quot, 1.0, False, args.tie,
                      args.tie_sub, args.init_scale, args.pick).to(dev)
    ref = PopAddALU(1, S, 2, 2, args.max_quot, 1.0, False, args.tie,
                    args.tie_sub, pick=args.pick).to(dev)
    model.sel_hard = args.sel_hard
    ref.construct()
    for p in ref.parameters():
        p.requires_grad_(False)

    n_par = sum(p.numel() for p in model.parameters())
    per_rep = (n_par - P) // P
    print(f"[{args.tag}] POP={P} N={N} S={S} ADD-ONLY pick={args.pick} "
          f"tie={args.tie} tie_sub={args.tie_sub} params={n_par:,} "
          f"(~{per_rep:,}/replica) train={len(tr_x)} held={len(he_x)} "
          f"units={len(units)} depth={model.depth()}", flush=True)

    try:
        from benchmark import ModelSpec, assert_model_state
        spec = ModelSpec(vocab_size=17, max_seq_len=64,
                         maximum_model_state_elements=500_000_000)
        n_state = assert_model_state(model, spec)
        print(f"[{args.tag}] assert_model_state OK: {n_state:,} / 500,000,000 "
              f"({100 * n_state / 5e8:.4f}%)", flush=True)
    except Exception as exc:                       # pragma: no cover
        print(f"[{args.tag}] assert_model_state FAILED: {exc}", flush=True)
        return 1

    if args.construct:
        model.construct()
        rs = eval_pop(model, xin[:args.eval_n], xt[:args.eval_n], nd, False,
                      args.eval_chunk)
        r = eval_pop(model, xin[:args.eval_n], xt[:args.eval_n], nd, True,
                     args.eval_chunk)
        rh = eval_pop(model, hin, ht, nd, True, args.eval_chunk,
                      diversity=True)
        print(f"[{args.tag}] CONSTRUCTED train_exact_soft={rs['best']:.4f} "
              f"train_exact_hard={r['best']:.4f} "
              f"held_exact_hard={rh['best']:.4f} mix={r['mix']:.4f} "
              f"held_diversity={rh['diversity']:.4f}", flush=True)
        if args.jsonl:
            with open(args.jsonl, "a") as fh:
                fh.write(json.dumps({
                    "tag": args.tag, "argv": sys.argv[1:], "mode": "construct",
                    "N": N, "slots": S, "pick": args.pick,
                    "train_exact_soft": round(rs["best"], 4),
                    "train_exact_hard": round(r["best"], 4),
                    "held_exact_hard": round(rh["best"], 4),
                    "held_diversity_ref": round(rh["diversity"], 4),
                    "depth": model.depth(), "params_per_replica": per_rep,
                }) + "\n")
        return 0

    groups = [{"params": [p for p in model.parameters() if p is not model.alpha],
               "lr": args.lr},
              {"params": [model.alpha],
               "lr": args.sel_lr if args.sel_lr is not None else args.lr}]
    opt = torch.optim.AdamW(groups, weight_decay=args.wd, betas=(0.9, 0.95))

    # measured collapse reference: the EXACT solution's output diversity on the
    # same held-out cohort under the same detector (RESUME: do not assume 1.0)
    with torch.no_grad():
        cref = PopAddALU(1, S, 2, 2, args.max_quot, 1.0, False, args.tie,
                         args.tie_sub, pick=args.pick).to(dev)
        cref.construct()
        div_ref = eval_pop(cref, hin, ht, nd, True, args.eval_chunk,
                           diversity=True)["diversity"]
        del cref
    print(f"[{args.tag}] MEASURED collapse reference (exact solution, this "
          f"cohort, this detector): held_diversity={div_ref:.4f}", flush=True)

    hist = []
    t0 = time.time()
    tstep = 0.0
    for step in range(1, args.steps + 1):
        model.sel_tau = args.sel_tau
        idx = torch.randint(0, xin.shape[0], (args.batch,), device=dev)
        bi, bt = xin[idx], xt[idx]
        if step == 11:
            torch.cuda.synchronize()
            tstep = time.time()
        model.hard = args.sthard
        loss = torch.zeros((), device=dev)
        if args.tf > 0:
            with torch.no_grad():
                ref.mode, ref.tape = 'record', []
                ref(bi, nd)
                ref.mode = None
            model.mode, model.tape = 'force', ref.tape
            model.tf_loss = torch.zeros(P, device=dev)
            model.tf_n, model.tf_p = 0, args.tf_p
            model(bi, nd)
            model.mode = None
            loss = loss + args.tf * (model.tf_loss / max(model.tf_n, 1)).mean()
        if args.sel > 0 or args.tf == 0:
            logits = model(bi, nd)
            mp = model.mix_probs(logits).clamp_min(1e-9)
            mix_ce = F.nll_loss(mp.log().reshape(-1, 10), bt.reshape(-1))
            loss = loss + max(args.sel, 0.0 if args.tf > 0 else 1.0) * mix_ce
            if args.tf == 0:
                loss = loss + F.cross_entropy(
                    logits.reshape(-1, 10),
                    bt[None].expand(P, *bt.shape).reshape(-1))
        model.hard = False
        opt.zero_grad(set_to_none=True)
        loss.backward()
        if args.clip:
            if args.global_clip:
                torch.nn.utils.clip_grad_norm_(model.parameters(), args.clip)
            else:
                pop_clip_(model, args.clip)
                torch.nn.utils.clip_grad_norm_([model.alpha], args.clip)
        opt.step()
        if step == 1 or step % args.log_every == 0 or step == args.steps:
            r = eval_pop(model, xin[:args.eval_n], xt[:args.eval_n], nd, True,
                         args.eval_chunk)
            rsoft = eval_pop(model, xin[:args.eval_n], xt[:args.eval_n], nd,
                             False, args.eval_chunk)
            w = F.softmax(model.alpha / model.sel_tau, 0)
            hist.append({"step": step, "loss": round(loss.item(), 4),
                         "train_exact": round(rsoft["best"], 4),
                         "train_exact_hard": round(r["best"], 4)})
            print(f"[{args.tag}] step={step:>6} loss={loss.item():.4f} "
                  f"train_exact={rsoft['best']:.4f} "
                  f"train_exact_hard={r['best']:.4f} mix={r['mix']:.4f} "
                  f"argmax={r['argmax']:.4f} "
                  f"n_basin={(r['per'] > 0.5).sum().item()}/{P} "
                  f"wmax={w.max().item():.3f} ({time.time()-t0:.0f}s)",
                  flush=True)
    torch.cuda.synchronize()
    ms = 1000 * (time.time() - tstep) / max(args.steps - 10, 1) \
        if args.steps > 10 else float('nan')

    out = {"tag": args.tag, "argv": sys.argv[1:], "pop": P, "N": N, "slots": S,
           "pick": args.pick, "lr": args.lr, "steps": args.steps,
           "ms_per_step": round(ms, 2), "secs": round(time.time() - t0, 1),
           "legal": bool(args.tf == 0), "hist": hist,
           "collapse_ref_diversity": round(div_ref, 4)}
    if not args.timing_only:
        tr = eval_pop(model, xin[:args.eval_n], xt[:args.eval_n], nd, True,
                      args.eval_chunk)
        trs = eval_pop(model, xin[:args.eval_n], xt[:args.eval_n], nd, False,
                       args.eval_chunk)
        he = eval_pop(model, hin, ht, nd, True, args.eval_chunk,
                      diversity=True)
        hes = eval_pop(model, hin, ht, nd, False, args.eval_chunk)
        with torch.no_grad():
            ref.mode, ref.tape = 'record', []
            ref(xin[:256], nd)
            ref.mode = None
            model.mode, model.tape = 'force', ref.tape
            model.tf_loss, model.tf_n, model.tf_p = \
                torch.zeros(P, device=dev), 0, 1.0
            model(xin[:256], nd)
            model.mode = None
            lce = (model.tf_loss / max(model.tf_n, 1)).cpu()
        acc = tr["per"].cpu()
        hacc = he["per"].cpu()
        order = torch.argsort(acc, descending=True)
        out.update({
            "train_exact_hard_best": round(float(acc.max()), 4),
            "train_exact_hard_mix": round(tr["mix"], 4),
            "train_exact_hard_argmax": round(tr["argmax"], 4),
            "train_exact_soft_best": round(trs["best"], 4),
            "train_exact_soft_mix": round(trs["mix"], 4),
            "held_exact_hard_best": round(float(hacc.max()), 4),
            "held_exact_hard_mix": round(he["mix"], 4),
            "held_exact_soft_mix": round(hes["mix"], 4),
            "held_diversity": round(he["diversity"], 4),
            "n_basin": int((acc > 0.5).sum()),
            "local_ce_best": round(float(lce.min()), 5),
            "local_ce_med": round(float(lce.median()), 5),
            "acc_sorted": [round(float(v), 3) for v in acc[order][:16]],
        })
        out.update(struct_scores(model, int(order[0]), nd_dig))
        print(f"[{args.tag}] FINAL " + " ".join(
            f"{k}={v}" for k, v in out.items()
            if k not in ("argv", "tag", "hist")), flush=True)
    else:
        print(f"[{args.tag}] TIMING ms_per_step={ms:.2f} pop={P} "
              f"batch={args.batch} "
              f"peak_mem={torch.cuda.max_memory_allocated()/2**30:.2f}GiB",
              flush=True)
    out["peak_gib"] = round(torch.cuda.max_memory_allocated() / 2 ** 30, 2)
    if args.jsonl:
        with open(args.jsonl, "a") as fh:
            fh.write(json.dumps(out) + "\n")
    return 0


