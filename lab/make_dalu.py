D_MODEL = 32
EMB_INIT = 0.02           # the hosted run's step-1 loss was 79.936, not ln 17
N_CARRY = 2
N_BORROW = 2
MAX_QUOT = {max_quot}     # alphabet of the learned quotient digit
TRAIN_LOOPS_EASY = 3
TRAIN_LOOPS_DEEP = {train_loops}
EVAL_LOOPS = {eval_loops}
DIGIT_TAU = 0.5
IDENTITY_INIT = 5.0
CONS_W = 0.1
CONS_J = 8
CONS_LOOPS = 4
SEL_EPS = 1e-6
SEL_THRESH_EASY = -3.0
SEL_THRESH_DEEP = 0.0
