#!/usr/bin/env python
"""Emit `submissions/hard-digitalu-hf1/submission.py` -- `DigitALU` at
Hard-faithful scale with every correction this project earned applied at once.

  parser (MarkerPointer, `explore/digit-carry`, verified 1.000 at T=16/32/64)
    -> DigitALU x k   -- tree:quotient graph (`explore/alu-depth`)
    -> counted-halting depth controller (`explore/depth-controller`, MAX_T=64)

DIFFERENCES FROM `submissions/depth-controller`, and why each one is here:

  * **tree:quotient instead of serial.**  The reduction was 80-86% of the
    sequential depth and 10 of its 11 tied conditional subtractions are no-ops.
    `alu-depth` replaced them with a balanced product tree plus one learned
    quotient digit and one subtraction: same hypothesis class, same discrete
    alphabet, constructed ceiling 1.000 soft AND argmax-hard, and at these
    slot counts **129 sequential soft steps instead of 1,537** (S=7).
  * **untied.**  `alu-credit` measured that weight ties help *repair* near a
    solution and HURT learning from random init (the one seed that succeeds
    untied fails when tied, `local_ce` 0.0050 -> 0.1187).  Two different
    problems; the ties are not carried across.
  * **small embedding init.**  `nn.Embedding`'s default `N(0,1)` put the hosted
    Hard run's step-1 loss at 79.936 instead of `ln 17 = 2.833`.  This model's
    head is not tied to the embedding, so the toll is smaller here than for the
    baseline, but the init is fixed anyway -- it is free.
  * **a chosen batch size** -- the evaluator's DataLoader has no
    `persistent_workers`, so batch size is a free throughput knob.

Everything is learned from random init.  No modular-exponentiation routine, no
digit-multiplication rule, no carry rule, no lookup of answers, no `torch.load`.
The construction used in the lab to certify the ceiling appears nowhere here.

Usage:  python lab/make_dalu.py --loops 16 --batch-size 128 --max-steps 800
"""

